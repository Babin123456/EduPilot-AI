const COLORS = {
  primary: [0, 96, 181] as [number, number, number],     // #0060B5
  secondary: [140, 198, 63] as [number, number, number],  // #8CC63F
  dark: [15, 23, 42] as [number, number, number],         // slate-900
  gray: [100, 116, 139] as [number, number, number],      // slate-500
  light: [241, 245, 249] as [number, number, number],     // slate-100
  white: [255, 255, 255] as [number, number, number],
  red: [239, 68, 68] as [number, number, number],
  green: [34, 197, 94] as [number, number, number],
  amber: [245, 158, 11] as [number, number, number],
};

function addHeader(doc: jsPDF, title: string, subtitle: string) {
  const pageWidth = doc.internal.pageSize.getWidth();
  
  // Top accent bar
  doc.setFillColor(...COLORS.primary);
  doc.rect(0, 0, pageWidth, 4, 'F');
  doc.setFillColor(...COLORS.secondary);
  doc.rect(0, 4, pageWidth, 2, 'F');

  // University name
  doc.setFontSize(18);
  doc.setFont('times', 'bold');
  doc.setTextColor(...COLORS.primary);
  doc.text('ADAMAS UNIVERSITY', pageWidth / 2, 22, { align: 'center' });

  // Subtitle line
  doc.setFontSize(8);
  doc.setFont('times', 'normal');
  doc.setTextColor(...COLORS.gray);
  doc.text('School of Engineering & Technology • Computer Science & Engineering', pageWidth / 2, 28, { align: 'center' });

  // Divider
  doc.setDrawColor(...COLORS.primary);
  doc.setLineWidth(0.5);
  doc.line(20, 32, pageWidth - 20, 32);

  // Document title
  doc.setFontSize(14);
  doc.setFont('times', 'bold');
  doc.setTextColor(...COLORS.dark);
  doc.text(title, pageWidth / 2, 42, { align: 'center' });

  // Document subtitle
  if (subtitle) {
    doc.setFontSize(9);
    doc.setFont('times', 'normal');
    doc.setTextColor(...COLORS.gray);
    doc.text(subtitle, pageWidth / 2, 48, { align: 'center' });
  }


  return 54; // Y position after header
}

function addFooter(doc: jsPDF, pageNum?: number) {
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const totalPages = doc.getNumberOfPages();

  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);

    // Bottom accent bar
    doc.setFillColor(...COLORS.primary);
    doc.rect(0, pageHeight - 6, pageWidth, 4, 'F');
    doc.setFillColor(...COLORS.secondary);
    doc.rect(0, pageHeight - 8, pageWidth, 2, 'F');

    // Footer text
    doc.setFontSize(7);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...COLORS.gray);
    doc.text('Generated by EduPilot AI — Adamas University', 20, pageHeight - 12);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - 20, pageHeight - 12, { align: 'right' });
  }
}

function addMetadataBox(doc: jsPDF, y: number, metadata: Record<string, string>) {
  const pageWidth = doc.internal.pageSize.getWidth();
  const boxWidth = pageWidth - 40;
  const entries = Object.entries(metadata);
  const boxHeight = 8 + entries.length * 7;

  doc.setFillColor(...COLORS.light);
  doc.setDrawColor(200, 210, 220);
  doc.roundedRect(20, y, boxWidth, boxHeight, 3, 3, 'FD');

  let currentY = y + 7;
  entries.forEach(([key, value]) => {
    doc.setFontSize(8);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...COLORS.gray);
    doc.text(`${key}:`, 26, currentY);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...COLORS.dark);
    doc.text(value, 80, currentY);
    currentY += 7;
  });

  return y + boxHeight + 6;
}

function addSectionTitle(doc: jsPDF, y: number, title: string, emoji?: string) {
  if (y > doc.internal.pageSize.getHeight() - 40) {
    doc.addPage();
    y = 20;
  }
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...COLORS.primary);
  const label = emoji ? `${emoji} ${title}` : title;
  doc.text(label, 20, y);
  doc.setDrawColor(...COLORS.secondary);
  doc.setLineWidth(0.3);
  doc.line(20, y + 2, doc.internal.pageSize.getWidth() - 20, y + 2);
  return y + 8;
}

function addParagraph(doc: jsPDF, y: number, text: string, maxWidth?: number) {
  const pageWidth = doc.internal.pageSize.getWidth();
  const width = maxWidth || pageWidth - 40;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...COLORS.dark);
  const lines = doc.splitTextToSize(text, width);
  
  for (const line of lines) {
    if (y > doc.internal.pageSize.getHeight() - 30) {
      doc.addPage();
      y = 20;
    }
    doc.text(line, 20, y);
    y += 5;
  }
  return y + 2;
}

function addBulletList(doc: jsPDF, y: number, items: string[]) {
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...COLORS.dark);
  const pageWidth = doc.internal.pageSize.getWidth();

  for (const item of items) {
    if (y > doc.internal.pageSize.getHeight() - 30) {
      doc.addPage();
      y = 20;
    }
    doc.setFillColor(...COLORS.primary);
    doc.circle(24, y - 1.5, 1.2, 'F');
    const lines = doc.splitTextToSize(item, pageWidth - 50);
    for (const line of lines) {
      doc.text(line, 28, y);
      y += 5;
    }
    y += 1;
  }
  return y + 2;
}

